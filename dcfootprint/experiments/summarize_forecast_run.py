"""Write report/RUN_SUMMARY.md for a forecasting run from its metric and manifest files.

Run: python dcfootprint/experiments/summarize_forecast_run.py runs/fresh_run_2026-09-27
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

COLS = ["MAE", "RMSE", "WMAPE_pct", "Bias", "MASE", "sMAPE_pct", "MedAE", "Pearson_r", "PICP", "CRPS"]


def fmt_table(df: pd.DataFrame) -> str:
    head = "| " + " | ".join(df.columns) + " |\n|" + "---|" * len(df.columns) + "\n"
    rows = []
    for _, r in df.iterrows():
        cells = []
        for c in df.columns:
            v = r[c]
            cells.append("—" if pd.isna(v) else (f"{v:,.3f}" if isinstance(v, float) and abs(v) < 10 else
                                                 f"{v:,.1f}" if isinstance(v, float) else str(v)))
        rows.append("| " + " | ".join(cells) + " |")
    return head + "\n".join(rows)


def main(run: Path) -> None:
    run = Path(run)
    m = pd.read_csv(run / "metrics" / "all_models_per_region.csv")
    man = json.loads((run / "manifest" / "run_manifest.json").read_text(encoding="utf-8"))
    fails = pd.read_csv(run / "metrics" / "failures.csv")
    z = m[m["level"] == "zones"]
    L = [f"# RUN_SUMMARY — {run.name}", "",
         "*Generated by `dcfootprint/experiments/summarize_forecast_run.py` from this folder's metric and manifest files.*", "",
         "## What ran where", "",
         "| model | repo | environment | status |", "|---|---|---|---|"]
    for k, v in man["models"].items():
        L.append(f"| {k} | {v.get('repo')} | {v.get('env', '—')} | {v.get('status')} |")
    L += ["",
          f"- counterfactual-policy `{man['repos']['counterfactual-policy']['branch']}` @ `{man['repos']['counterfactual-policy']['commit'][:7]}`"
          f"{' (uncommitted changes in dcfootprint/src)' if man['repos']['counterfactual-policy']['dirty'] else ''}; "
          f"Co-RE @ `{man['repos']['Co-RE']['commit'][:7]}` (read-only).",
          "- **`chronos-2` and `nexus` are different models, reported separately.** The Co-RE cache column named "
          "\"Nexus\" is Chronos-2 in the Nexus slot and appears here only as `chronos-2`. The real multi-agent Nexus "
          "was **not run** (below).", "",
          "## Deviations from the run prompt (all deliberate, all verified)", "",
          "1. **No scaffold zip exists** (searched the project and Downloads); the folder was created with the §6 layout.",
          "2. **\"New data\" adds no new forecastable series.** Compute Atlas, the EU EED report and AWARE 2.0 are "
          "cross-sections; the only monthly series are Ember electricity and CO2 intensity, which Co-RE's cached run "
          "already covers for the same US / India / Europe zones. So old-vs-new collapses to one Ember series set, "
          "forecast at two grains: dcfootprint (Ember zones + regional aggregate; EU-27 only) and Co-RE (95 zones incl. "
          "non-EU Europe; 24 G3P water basins).",
          "3. **xLSTM, TimesFM 2.5, Chronos-2 were not re-run**: their fresh run on the same series would reproduce the "
          "cache. The cache was re-scored with this run's metric set; its per-zone RMSE reproduces Co-RE's own "
          "`model_comparison_region.csv` exactly (856/856 zone-model pairs, max abs diff 0.0).",
          "4. **Real Nexus not run.** One gemma4:26b call via Ollama took 534 s on this CPU (3,985 tokens, ~8.6 tok/s, "
          "visible answer empty after the thinking tokens). The notebook's 5 agents x N_SPLITS=6 per series put the "
          "country-level run alone at days of compute; the 95-zone run far longer. Needs a GPU or a smaller/"
          "non-thinking model — decision pending.",
          "5. **Probabilistic metrics only where a predictive distribution exists**: PICP (80% interval) and CRPS "
          "(Gaussian closed form) for the fresh dcfootprint models; the Co-RE cache holds point forecasts only, so "
          "PICP/CRPS are blank there — not estimated.",
          "6. **No water forecast for the US/EU** — no US/EU water time series exists in the project. Water appears "
          "only for Co-RE's 24 G3P basins (cached).", "",
          "## Fresh dcfootprint SARIMA: fit validity (found and fixed during this run)", "",
          f"{len(fails)} of the SARIMA fits are recorded failures and excluded (never scored as zero or clipped):", ""]
    for reason, n in fails.groupby("reason").size().items():
        L.append(f"- {n} x {reason}")
    L += ["",
          "Found by investigating implausible metrics, not by tuning: a non-converged Germany fit forecast an "
          "oscillating 225,000 GWh/month (actual ~45,000); a 'converged' Texas fit sat on the unit boundary "
          "(all coefficients = +-1, log-likelihood 0) and forecast 0 GWh. Fixes: MLE must converge (maxiter 500), "
          "coefficients off the unit boundary, finite SEs, missing months kept as NaN instead of dropped.", "",
          "## Metrics — zones (the regional aggregate series are reported in `metrics/all_models_per_region.csv`, level=aggregate)", ""]
    for res in ["electricity", "carbon", "water"]:
        t = z[z["resource"] == res].sort_values(["region", "RMSE"])
        if len(t):
            L += [f"### {res}", "", fmt_table(t[["model", "region", "n_series"] + COLS]), ""]
    L += ["Units: electricity GWh/month, carbon gCO2/kWh (EU: CO2e), water mm TWS. MASE < 1 beats the in-sample "
          "seasonal naive. PICP nominal 0.80.", "",
          "## Open items (not silently dropped)", "",
          "- **GADM USA**: downloaded (112,730,112 bytes, layer ADM_ADM_1) and used by the US account — closed.",
          "- **Aqueduct (c)**: resolved from the technical note (Kuzma et al. 2023): raw water stress is capped to [0,1] "
          "(p.11) and future inputs are bias-corrected to the baseline (p.10) -> Q1 scenarios will use the 0-5 scores; "
          "implementation pending.",
          "- **Real Nexus** (above), **US/EU water series** (none exist), **xLSTM expanding-window backtest** (~3 h, "
          "not run).",
          "- dcfootprint `project/hierarchy.py` (feeds Q3) lacks the convergence/degeneracy checks added here; its "
          "cached India forecasts were audited (all DC-state values 328-791 g/kWh, no zeros) but the check should be "
          "ported and the Q3 forecast rebuilt.", ""]
    (run / "report").mkdir(exist_ok=True)
    (run / "report" / "RUN_SUMMARY.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote", run / "report" / "RUN_SUMMARY.md")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
